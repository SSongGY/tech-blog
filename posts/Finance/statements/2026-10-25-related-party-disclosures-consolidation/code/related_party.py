"""특수관계자 거래가 별도재무제표와 연결재무제표에 다르게 남는 과정을 계산한다.

마바홀딩스·사아전자·자차물산은 실재하지 않는 회사다. 금액 단위는 백만원이고,
숫자는 연결에서 사라지는 거래와 남는 거래를 가르려고 만든 것이다.

K-IFRS 제1024호 문단 4(연결 제거)·9(정의)·11(특수관계자가 아닌 경우)·
13(지배관계)·17(주요 경영진 보상)·18·19(범주별 공시)의 구조를 따른다.
"""

import unicodedata


def width(text):
    return sum(2 if unicodedata.east_asian_width(ch) in "WF" else 1 for ch in text)


def pad(text, size, align="left"):
    gap = max(0, size - width(text))
    return text + " " * gap if align == "left" else " " * gap + text


def table(cols, sizes, rows, indent="    "):
    print(indent + "".join(pad(c, s) for c, s in zip(cols, sizes)))
    for row in rows:
        print(indent + "".join(pad(str(c), s) for c, s in zip(row, sizes)))


def money(value):
    return f"{value:,}"


def head(title):
    print()
    print(title)


# ---------------------------------------------------------------- 그룹 구성

# (상대방, 관계, 연결 범위에 들어오는가)
PARTIES = [
    ("마바홀딩스", "지배기업 — 사아전자 지분 100%", True),
    ("사아전자", "종속기업 — 연결 대상", True),
    ("자차물산", "관계기업 — 사아전자가 지분 30% 보유", False),
    ("주요 경영진", "마바홀딩스·사아전자의 이사와 임원", False),
]

# (거래 내용, 거래 당사자, 금액, 연결실체 내부인가)
DEALS = [
    ("제품 매출", "사아전자 → 마바홀딩스", 10_000, True),
    ("매출채권 잔액", "사아전자 → 마바홀딩스", 2_500, True),
    ("자금 대여", "마바홀딩스 → 사아전자", 30_000, True),
    ("이자수익", "마바홀딩스 → 사아전자", 1_500, True),
    ("지급보증", "마바홀딩스 → 사아전자", 20_000, True),
    ("제품 매출", "사아전자 → 자차물산", 20_000, False),
    ("매출채권 잔액", "사아전자 → 자차물산", 6_000, False),
]

SEPARATE_SALES = {
    "마바홀딩스": {"외부": 15_000, "내부": 0},
    "사아전자": {"외부": 40_000, "내부": 30_000},  # 마바홀딩스 10,000 + 자차물산 20,000
}

COMPENSATION = [
    ("단기종업원급여", 1_200),
    ("퇴직급여", 200),
    ("기타 장기급여", 50),
    ("해고급여", 0),
    ("주식기준보상", 300),
]

NOT_RELATED = [
    ("임원을 함께 두고 있을 뿐인 두 기업", "겸직만으로는 특수관계가 아니다"),
    ("같은 공동기업을 공동지배하는 두 참여자", "서로에게는 특수관계자가 아니다"),
    ("주거래은행·노동조합·전기 공급자", "통상적 업무관계뿐이면 아니다"),
    ("매출의 절반을 차지하는 대형 고객", "경제적 의존만으로는 아니다"),
]

# ------------------------------------------------------- [1] 누가 특수관계자인가

head("[1] 마바홀딩스 그룹 — 특수관계자와 연결 범위는 같지 않다")
table(
    ["상대방", "관계 (문단 9)", "연결 범위"],
    [16, 42, 12],
    [(name, rel, "들어온다" if inside else "밖") for name, rel, inside in PARTIES],
)
print("    관계기업과 주요 경영진은 특수관계자이지만 연결 대상은 아니다 — 이 어긋남이 뒤의 차이를 만든다")

head("[2] 특수관계자가 아닌 경우 (문단 11)")
table(["상대방", "왜 아닌가"], [42, 40], NOT_RELATED)

# ------------------------------------- [3] 연결에서 사라지는 거래와 남는 거래

head("[3] 당기 거래 — 연결재무제표를 만들 때 어느 것이 제거되는가 (문단 4)")
table(
    ["거래", "당사자", "금액", "연결 작성 시"],
    [16, 26, 12, 16],
    [
        (kind, who, money(amount), "제거된다" if internal else "남는다")
        for kind, who, amount, internal in DEALS
    ],
)
removed = sum(1 for *_, internal in DEALS if internal)
print(f"    일곱 건 중 {removed}건이 연결재무제표에서 사라진다")
print("    제거 기준은 '특수관계자인가'가 아니라 '연결실체 안의 거래인가'다")

# --------------------------------------------- [4] 매출이 두 재무제표에서 갈린다

head("[4] 매출 — 별도 단순합산과 연결이 갈리는 폭")
simple_sum = sum(v["외부"] + v["내부"] for v in SEPARATE_SALES.values())
intragroup = 10_000  # 사아전자 → 마바홀딩스
consolidated = simple_sum - intragroup
rows = []
for name, sales in SEPARATE_SALES.items():
    rows.append((name, money(sales["외부"]), money(sales["내부"]), money(sales["외부"] + sales["내부"])))
table(["재무제표", "외부 매출", "특수관계자 매출", "별도 매출 합계"], [16, 16, 20, 18], rows)
print(f"    두 회사 별도 매출 단순합산 {money(simple_sum)}")
print(f"    (-) 연결실체 내부 매출 {money(intragroup)}  ← 사아전자가 마바홀딩스에 판 몫")
print(f"    = 연결 매출 {money(consolidated)}")
print(f"    자차물산(관계기업)에 판 20,000은 연결실체 밖이라 연결 매출에 그대로 남는다")

# ------------------------------------- [5] 같은 거래, 주석에 적히는 곳이 다르다

head("[5] 어느 주석에 적히는가 — 같은 거래가 재무제표마다 달리 보인다")
rows = [
    ("사아전자 → 마바홀딩스 매출 10,000", "공시", "제거되어 공시하지 않는다"),
    ("마바홀딩스 → 사아전자 이자수익 1,500", "공시", "제거되어 공시하지 않는다"),
    ("마바홀딩스 → 사아전자 지급보증 20,000", "공시", "제거되어 공시하지 않는다"),
    ("사아전자 → 자차물산 매출 20,000", "공시", "공시한다"),
    ("주요 경영진 보상", "공시", "공시한다"),
    ("지배기업 마바홀딩스의 명칭", "거래 없어도 공시", "해당 없음"),
]
table(["항목", "사아전자 별도 주석", "마바홀딩스 연결 주석"], [38, 22, 26], rows)
print("    연결 주석만 보면 그룹 안에서 오간 거래는 보이지 않는다 — 별도재무제표를 따로 열어야 한다")
print("    지배기업과 종속기업의 관계는 거래 유무와 관계없이 공시한다 (문단 13)")

# ----------------------------------------------- [6] 범주별로 나누어 공시한다

head("[6] 문단 19 — 공시할 때 쓰는 범주 (사아전자 별도재무제표 기준)")
rows = [
    ("지배기업", "마바홀딩스", money(10_000), money(2_500)),
    ("관계기업", "자차물산", money(20_000), money(6_000)),
    ("주요 경영진", "이사·임원", money(sum(a for _, a in COMPENSATION)), "0"),
]
table(["범주", "상대방", "당기 거래금액", "기말 채권 잔액"], [16, 16, 18, 18], rows)
print("    금액을 한 줄로 합치지 않고 범주로 나누는 이유는, 누구와의 거래인지가 곧 정보이기 때문이다")

head("[7] 문단 17 — 주요 경영진 보상은 다섯 분류로 나눈다")
table(
    ["분류", "금액"],
    [22, 14],
    [(label, money(amount)) for label, amount in COMPENSATION],
)
print(f"    합계 {money(sum(a for _, a in COMPENSATION))}")
print("    총액만 적는 것으로는 부족하고, 다섯 분류 금액을 함께 적어야 한다")
